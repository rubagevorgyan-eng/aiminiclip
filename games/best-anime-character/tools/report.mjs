// Coverage report -> DATABASE_PROGRESS.md (generated; edit this script, not the file).   node tools/report.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadABC } from './load.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ABC = loadABC({ withCharacters: true }), CFG = ABC.config, ENG = ABC.engine;
const B = ENG.build(ABC.characters), all = ABC.characters, E = B.entries;
const M = JSON.parse(readFileSync(join(HERE, 'imports', 'manifest.json'), 'utf8'));
const uniq = list => new Set(list.map(e => e.charId)).size;
const play = E.filter(ENG.playable), queue = E.filter(e => !ENG.playable(e));
const playChars = new Set(play.map(e => e.charId));
const queueOnly = new Set(queue.map(e => e.charId).filter(c => !playChars.has(c)));
const animeChars = new Set(play.filter(e => e.anime === 'shown' || e.anime === 'anime-only').map(e => e.charId));
const notShownOnly = [...new Set(E.map(e => e.charId))].filter(c => E.filter(e => e.charId === c).every(e => e.anime === 'not-shown'));
const unknownAnime = [...playChars].filter(c => !animeChars.has(c));
const noImgChars = [...new Set(E.map(e => e.charId))].filter(c => E.filter(e => e.charId === c).every(e => !e.img));
const incomplete = play.filter(e => { const s = e.stats || {}; return !s.ap || !s.speed || !s.speed.combat || !s.durability; });
const byBy = k => play.filter(e => e.review.by === k).length;
const stars = {}; for (const e of ENG.pool(play, 'all')) stars[e.game.star] = (stars[e.game.star] || 0) + 1;
const dup = B.warnings.filter(w => w.includes('possible duplicate')).length;
const n = x => x.toLocaleString('en-US');
const reasons = {};
for (const e of queue) {
  const notes = (e.review.notes || []).join(' ');
  const k = /Legacy entry/.test(notes) ? 'legacy tier-only entry, no VS page matched' : /Extraction failed/.test(notes) ? 'extraction failed' :
    /parts for/.test(notes) ? 'key / value count mismatch on the profile' : /Manual review: (.*?)\./.exec(notes) ? 'VS tier: ' + /Manual review: (.*?)\./.exec(notes)[1] : 'other';
  reasons[k] = (reasons[k] || 0) + 1;
}

const seriesRows = Object.entries(CFG.series).map(([sid, s]) => {
  const es = E.filter(e => e.series === sid), m = M.series[sid] || {};
  const pc = uniq(es.filter(ENG.playable));
  return `| ${s.name} | ${n(m.listed || 0)} | ${n(m.characterPages || 0)} | ${n(uniq(es))} | ${n(pc)} | ${n(es.length)} | ${n(es.filter(e => !ENG.playable(e)).length)} | ${m.imported || '—'} |`;
}).join('\n');
const excl = {}; for (const m of Object.values(M.series)) for (const [k, v] of Object.entries(m.excluded || {})) { const kk = k.startsWith('non-canonical') ? 'non-canonical origin (films, games, GT, crossovers…)' : k; excl[kk] = (excl[kk] || 0) + v; }

const md = `# Character database progress

_Generated by \`node tools/report.mjs\` on ${M.generated}. Do not edit by hand._

## Coverage

| Measure | Count |
|---|---|
| Unique canonical characters (all records, any status) | **${n(uniq(E))}** |
| Character-version records | ${n(E.length)} |
| **Verified playable characters** (unique, ≥1 verified version) | **${n(playChars.size)}** |
| — of which reviewer-verified versions / machine-verified versions | ${n(byBy('reviewer'))} / ${n(byBy('auto'))} |
| Characters only in the manual-review queue (not playable) | ${n(queueOnly.size)} |
| Versions awaiting manual review | ${n(queue.length)} |
| Anime-eligible playable characters (version confirmed shown) | ${n(animeChars.size)} |
| Playable characters whose anime status is unconfirmed (kept out of Anime only) | ${n(unknownAnime.length)} |
| Manga/manhwa-exclusive characters (every version not in the anime) | ${n(notShownOnly.length)} |
| Characters without artwork (fallback art) | ${n(noImgChars.length)} |
| Playable versions with missing/incomplete core stats (AP, combat speed or durability) | ${n(incomplete.length)} |
| Records removed as duplicates (same page + key as a reviewer entry; duplicate ids) | ${n(Object.values(M.removed).reduce((a, b) => a + b, 0))} |
| Possible duplicate characters flagged for review (same name, different id) | ${dup} |
| Legacy (first-version) entries replaced by imports / kept in review queue | ${M.legacy.replaced} / ${M.legacy.kept} |

The 1,000 target counts **unique verified playable characters**: ${n(playChars.size)} ${playChars.size >= 1000 ? '— target met' : '— target not met yet'}.
"Machine-verified" means the tier and key were parsed unambiguously from the cited VS Battles revision with a canonical
origin; no person has reviewed those entries.

## By series

| Series | VS pages listed | Character pages | Characters | Playable | Versions | In review | Imported |
|---|---|---|---|---|---|---|---|
${seriesRows}

## Playable characters by star (default pool: strongest verified version each)

| Star | Rarity | Characters |
|---|---|---|
${[1, 2, 3, 4, 5, 6, 7].map(s => `| ${s}★ | ${CFG.stars[s].name} | ${n(stars[s] || 0)} |`).join('\n')}

## Excluded during import (pages)

${Object.entries(excl).sort((a, b) => b[1] - a[1]).map(([k, v]) => `- ${k}: ${v}`).join('\n')}

## Batches

| Batch | Series | Status |
|---|---|---|
| 1 (Step 3) | 11 reviewer-verified test characters, 17 versions | done |
| 2 (Step 6) | all 19 series via VS Battles categories | done — ${M.generated}, ${n(E.length)} versions |
| Next | Manual-review queue (${n(queue.length)} versions); anime-status confirmation for "unknown" series; artwork licensing | pending |

## Source limitations

- VS Battles Wiki is a community wiki. Tiers are its assessments, not canon; each entry stores page, key and revision.
- The importer takes each profile's **latest key** (VS convention: last = latest/strongest listed version) plus a key named
  "Base" when present. Other keys are not imported yet.
- Anime status: only origins whose whole canon is animated (Naruto/Shippuden, The Seven Deadly Sins, Dragon Ball/Z and
  its films/Daima, Attack on Titan, Fullmetal Alchemist, Death Note) are marked shown; manga-only origins
  (Two Blue Vortex, JJK Modulo) are marked not shown; everything else is "unknown" and excluded from Anime only.
- Characters without a VS Battles profile in these categories are not in the database (no canon-feat scoring was done).
- Artwork: only the original roster's AniList images are kept (hotlinked; licence unconfirmed). New characters use fallback art.
- Light novel: Classroom of the Elite uses medium "novel".

## Unresolved research items (manual-review queue)

${Object.entries(reasons).sort((a, b) => b[1] - a[1]).map(([k, v]) => `- ${k}: ${v} versions`).join('\n')}
- Anime status "unknown" for ${n(unknownAnime.length)} playable characters (series not fully adapted; needs per-version confirmation).
- No licensed artwork for ${n(noImgChars.length)} characters (fallback art shown).

## Adding a series or character versions (no auction-engine changes)

1. Add the series to \`config.series\` in \`data/config.js\`: id, name, colour, VS Battles category (\`vs\`), canonical
   origins (\`canon\`), fully animated origins (\`animeDone\`), manga-only origins (\`mangaOnly\`), source \`medium\`.
2. \`node tools/build-data.mjs --series <id>\` (imports, caches, validates, writes \`data/characters/<id>.js\` and the
   script tag). For a hand-checked version, add it to \`tools/spec/verified.mjs\` (page + key + anime status) and rebuild.
3. \`node tools/check.mjs\`, \`node tools/simulate.mjs\`, \`node tools/report.mjs\`. Nothing in \`auction.js\`,
   \`draw.js\`, \`setup.js\` or the page needs to change.

## Validation

Run \`node tools/check.mjs\`, \`node tools/test-setup.mjs\`, \`node tools/test-auction.mjs\`. Last build: ${B.errors.length} errors,
${B.warnings.length} warnings (manual-review queue and possible duplicates).
`;
writeFileSync(join(HERE, '..', 'DATABASE_PROGRESS.md'), md);
console.log(md.split('## By series')[0]);
